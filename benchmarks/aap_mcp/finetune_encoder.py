"""Finetune a sentence transformer for type-pair prediction.

Contrastive learning: query embeddings are pushed close to the correct
(source_type, target_type) pair embedding, and away from other pairs
via in-batch negatives.

Requirements:
    pip install sentence-transformers>=3.0

Input files (same directory):
    - training_data.jsonl   — generated by generate_dataset.py
    - graph_snapshot.json   — frozen composition graph

Output:
    - encoder_model/        — finetuned sentence transformer

Usage:
    python finetune_encoder.py
    python finetune_encoder.py --base-model all-MiniLM-L6-v2 --epochs 10
"""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import torch
from datasets import Dataset
from sentence_transformers import (
    SentenceTransformer,
    SentenceTransformerTrainer,
    SentenceTransformerTrainingArguments,
)
from sentence_transformers.losses import MultipleNegativesRankingLoss
from sentence_transformers.util import cos_sim

# ── Paths ──────────────────────────────────────────────────────────────

HERE = Path(__file__).parent
GRAPH_PATH = HERE / "graph_snapshot.json"
DATA_PATH = HERE / "training_data.jsonl"
OUTPUT_DIR = HERE / "encoder_model"

# ── Defaults ───────────────────────────────────────────────────────────

BASE_MODEL = "all-MiniLM-L6-v2"
EPOCHS = 5
BATCH_SIZE = 64
LEARNING_RATE = 2e-5
WARMUP_RATIO = 0.1
DEV_FRACTION = 0.1
SEED = 42
SAVE_TOTAL_LIMIT = 2
LOGGING_STEPS = 10

# ── Type-pair text format ──────────────────────────────────────────────
# Must match run_benchmark_encoder.py exactly.

PAIR_TEMPLATE = "Source: {source} — {source_desc}. Target: {target} — {target_desc}."


def format_pair(source: str, target: str, entity_types: dict[str, str]) -> str:
    return PAIR_TEMPLATE.format(
        source=source,
        source_desc=entity_types.get(source, ""),
        target=target,
        target_desc=entity_types.get(target, ""),
    )


# ── Data loading ───────────────────────────────────────────────────────


def load_graph() -> dict:
    with open(GRAPH_PATH) as f:
        return json.load(f)


def load_training_data() -> list[dict]:
    examples = []
    with open(DATA_PATH) as f:
        for line in f:
            if line.strip():
                examples.append(json.loads(line))
    return examples


def extract_valid_pairs(graph: dict) -> set[tuple[str, str]]:
    """Extract (source_type, target_type) pairs from direct tool edges."""
    core_types = set(graph["entity_types"].keys())
    pairs: set[tuple[str, str]] = set()
    for tool in graph["tools"]:
        for inp in tool["input_types"]:
            for out in tool["output_types"]:
                if inp in core_types and out in core_types:
                    pairs.add((inp, out))
    return pairs


# ── Train / dev split ──────────────────────────────────────────────────


def split_train_dev(
    anchors: list[str],
    positives: list[str],
    dev_fraction: float,
    seed: int,
) -> tuple[Dataset, Dataset]:
    random.seed(seed)
    indices = list(range(len(anchors)))
    random.shuffle(indices)

    dev_size = int(len(indices) * dev_fraction)
    dev_idx = set(indices[:dev_size])

    train_a = [anchors[i] for i in range(len(anchors)) if i not in dev_idx]
    train_p = [positives[i] for i in range(len(positives)) if i not in dev_idx]
    dev_a = [anchors[i] for i in sorted(dev_idx)]
    dev_p = [positives[i] for i in sorted(dev_idx)]

    print(f"  Train split: {len(train_a)}")
    print(f"  Dev split:   {len(dev_a)}")

    train_ds = Dataset.from_dict({"anchor": train_a, "positive": train_p})
    dev_ds = Dataset.from_dict({"anchor": dev_a, "positive": dev_p})
    return train_ds, dev_ds


# ── Sanity check ───────────────────────────────────────────────────────


def sanity_check(
    model: SentenceTransformer,
    query: str,
    pair_text: str,
    source: str,
    target: str,
) -> None:
    query_emb = model.encode([query], convert_to_tensor=True)
    pair_emb = model.encode([pair_text], convert_to_tensor=True)
    sim = cos_sim(query_emb, pair_emb)[0][0].item()
    print(f"\nSanity check:")
    print(f"  Query:  {query}")
    print(f"  Pair:   {source} -> {target}")
    print(f"  Cosine: {sim:.4f}")


# ── Main ───────────────────────────────────────────────────────────────


def finetune(
    base_model: str = BASE_MODEL,
    epochs: int = EPOCHS,
    batch_size: int = BATCH_SIZE,
    learning_rate: float = LEARNING_RATE,
    seed: int = SEED,
):
    # ── Load data ──────────────────────────────────────────────────────

    graph = load_graph()
    entity_types = graph["entity_types"]
    valid_pairs = extract_valid_pairs(graph)
    raw_examples = load_training_data()

    print(f"Entity types:     {len(entity_types)}")
    print(f"Valid type pairs: {len(valid_pairs)}")
    print(f"Raw examples:     {len(raw_examples)}")

    # ── Build pair texts ───────────────────────────────────────────────

    pair_texts: dict[tuple[str, str], str] = {}
    for src, tgt in valid_pairs:
        pair_texts[(src, tgt)] = format_pair(src, tgt, entity_types)

    # ── Map examples to (query, pair_text) ─────────────────────────────

    anchors: list[str] = []
    positives: list[str] = []
    skipped = 0

    for ex in raw_examples:
        key = (ex["source_type"], ex["target_type"])
        if key not in pair_texts:
            skipped += 1
            continue
        anchors.append(ex["query"])
        positives.append(pair_texts[key])

    if skipped:
        print(f"Skipped:          {skipped} (type pair not in graph)")
    print(f"Usable examples:  {len(anchors)}")

    # ── Split ──────────────────────────────────────────────────────────

    train_dataset, dev_dataset = split_train_dev(
        anchors, positives, DEV_FRACTION, seed,
    )

    # ── Model + loss ───────────────────────────────────────────────────

    model = SentenceTransformer(base_model)
    loss = MultipleNegativesRankingLoss(model)

    use_fp16 = torch.cuda.is_available()

    training_args = SentenceTransformerTrainingArguments(
        output_dir=str(OUTPUT_DIR),
        num_train_epochs=epochs,
        per_device_train_batch_size=batch_size,
        learning_rate=learning_rate,
        warmup_ratio=WARMUP_RATIO,
        eval_strategy="epoch",
        save_strategy="epoch",
        save_total_limit=SAVE_TOTAL_LIMIT,
        logging_steps=LOGGING_STEPS,
        load_best_model_at_end=True,
        seed=seed,
        fp16=use_fp16,
    )

    trainer = SentenceTransformerTrainer(
        model=model,
        args=training_args,
        train_dataset=train_dataset,
        eval_dataset=dev_dataset,
        loss=loss,
    )

    # ── Finetune ───────────────────────────────────────────────────────

    device = "GPU" if torch.cuda.is_available() else "CPU"
    print(f"\nFinetuning {base_model} on {device}")
    print(f"  Epochs: {epochs}  Batch: {batch_size}  LR: {learning_rate}  FP16: {use_fp16}")

    trainer.train()
    model.save_pretrained(str(OUTPUT_DIR))
    print(f"\nModel saved to {OUTPUT_DIR}")

    # ── Verify ─────────────────────────────────────────────────────────

    sample = raw_examples[0]
    key = (sample["source_type"], sample["target_type"])
    if key in pair_texts:
        sanity_check(model, sample["query"], pair_texts[key], key[0], key[1])


def main():
    parser = argparse.ArgumentParser(description="Finetune type-pair encoder")
    parser.add_argument("--base-model", default=BASE_MODEL)
    parser.add_argument("--epochs", type=int, default=EPOCHS)
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--lr", type=float, default=LEARNING_RATE)
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    finetune(
        base_model=args.base_model,
        epochs=args.epochs,
        batch_size=args.batch_size,
        learning_rate=args.lr,
        seed=args.seed,
    )


if __name__ == "__main__":
    main()
